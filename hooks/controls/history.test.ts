import { expect, test } from 'claude-code/testing'

import { historyMessages, isResumed, rowsToMessages } from './history'

const rows = [
  { role: 'user', text: 'Add a retry to the uploader', toolUses: [] },
  {
    role: 'assistant',
    text: 'Looking at the uploader.',
    toolUses: [{ id: 't1', name: 'Read', input: { file_path: 'a.ts' }, text: 'file body' }],
  },
  { role: 'user', text: '', toolUses: [], toolResults: [{ tool_use_id: 't1', text: 'file body', isError: false }] },
  { role: 'assistant', text: '', toolUses: [{ id: 't2', name: 'Edit', input: {} }] },
  { role: 'user', text: '<system-reminder>Plan mode is active.</system-reminder>', toolUses: [] },
  { role: 'user', text: '<command-name>/model</command-name>\n<command-args>opus</command-args>', toolUses: [] },
  { role: 'user', text: 'Caveat: The messages below were generated by the user while running local commands.', toolUses: [] },
  { role: 'user', text: '[Request interrupted by user]', toolUses: [] },
  { role: 'user', text: '[orchestrator] Task 3 "Fix docs" finished: done. Call status with id 3.', toolUses: [] },
  { role: 'assistant', text: 'Task 3 is done; docs fixed.', toolUses: [] },
  { role: 'user', text: '<system-reminder>ctx</system-reminder>What changed?', toolUses: [], isMeta: false },
  { role: 'user', text: 'hidden', toolUses: [], isMeta: true },
  { role: 'assistant', text: '   ', toolUses: [] },
  null,
  { role: 'tool', text: 'x' },
]

test('keeps prompts and replies, drops tool rows, meta and empties', async () => {
  const m = rowsToMessages(rows)
  expect(m.map(x => [x.role, x.text])).toEqual([
    ['user', 'Add a retry to the uploader'],
    ['assistant', 'Looking at the uploader.'],
    ['system', '[orchestrator] Task 3 "Fix docs" finished: done. Call status with id 3.'],
    ['assistant', 'Task 3 is done; docs fixed.'],
    ['user', 'What changed?'],
  ])
  expect(m.every(x => x.type === 'msg' && x.source === 'history')).toBe(true)
})

test('uses a row time when present, else 0', async () => {
  const m = rowsToMessages([
    { role: 'user', text: 'a', toolUses: [], timestamp: '2026-10-25T12:00:00Z' },
    { role: 'user', text: 'b', toolUses: [], at: 1_700_000_000_000 },
    { role: 'user', text: 'c', toolUses: [] },
  ])
  expect(m.map(x => x.at)).toEqual([Date.parse('2026-10-25T12:00:00Z'), 1_700_000_000_000, 0])
})

test('clips long text and keeps the newest rows under the cap', async () => {
  const long = rowsToMessages([{ role: 'assistant', text: 'x'.repeat(5000), toolUses: [] }])
  expect(long[0]?.text.length).toBe(4000)
  const many = Array.from({ length: 10 }, (_, i) => ({ role: 'user', text: `m${i}`, toolUses: [] }))
  expect(rowsToMessages(many, 3).map(x => x.text)).toEqual(['m7', 'm8', 'm9'])
  expect(rowsToMessages(many, 0)).toEqual([])
})

test('historyMessages and isResumed read the session and survive errors', async () => {
  const fake = (read: () => Promise<unknown>) => ({ session: { messages: read } }) as never
  const full = fake(async () => rows)
  expect((await historyMessages(full, 2)).length).toBe(2)
  expect(await isResumed(full)).toBe(true)
  expect(await isResumed(fake(async () => []))).toBe(false)
  const broken = fake(async () => {
    throw new Error('nope')
  })
  expect(await historyMessages(broken)).toEqual([])
  expect(await isResumed(broken)).toBe(false)
})
